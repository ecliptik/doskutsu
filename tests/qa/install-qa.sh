    echo "        Cell 1.12 will do a one-time cold render on the bench (wizard fallback)."
    HQ_STATE="skipped"
  fi
else
  echo "  NOTE: no HQ (22050_2) cache in payload -- cell 1.12 will cold-render (wizard fallback)."
